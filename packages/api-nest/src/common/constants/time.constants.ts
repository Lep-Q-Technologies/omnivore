/**
 * Time Constants
 *
 * Common time durations in milliseconds for use across the application.
 */

// Seconds
export const ONE_SECOND_MS = 1000
export const THIRTY_SECONDS_MS = 30 * ONE_SECOND_MS

// Minutes
export const ONE_MINUTE_MS = 60 * ONE_SECOND_MS
export const FIVE_MINUTES_MS = 5 * ONE_MINUTE_MS
export const TEN_MINUTES_MS = 10 * ONE_MINUTE_MS
export const THIRTY_MINUTES_MS = 30 * ONE_MINUTE_MS

// Hours
export const ONE_HOUR_MS = 60 * ONE_MINUTE_MS
export const TWELVE_HOURS_MS = 12 * ONE_HOUR_MS
export const TWENTY_FOUR_HOURS_MS = 24 * ONE_HOUR_MS
export const FORTY_EIGHT_HOURS_MS = 48 * ONE_HOUR_MS

// Days
export const ONE_DAY_MS = TWENTY_FOUR_HOURS_MS
export const SEVEN_DAYS_MS = 7 * ONE_DAY_MS
export const THIRTY_DAYS_MS = 30 * ONE_DAY_MS
